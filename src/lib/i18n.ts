/** تطبيع كود لغة: "EN-US" → "en" */
function normLang(lang: string | null | undefined): string {
  return String(lang ?? "").trim().toLowerCase().split(/[-_]/)[0];
}

/** تعريف لغة بكودها مع سقوط للعربية (الافتراضية) */
export function langOf(code: string | null | undefined): LanguageDef {
  const c = normLang(code);
  return LANGUAGES.find((l) => l.code === c) ?? LANGUAGES[0];
}

